// Run with GSETTINGS_BACKEND=memory; no user settings are read or written.
import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import {exportConfiguration, importConfiguration, readConfiguration, writeConfiguration} from '../lib/configuration.js';
const source = Gio.SettingsSchemaSource.new_from_directory(`${GLib.get_current_dir()}/schemas`, Gio.SettingsSchemaSource.get_default(), false);
const settings = new Gio.Settings({settings_schema: source.lookup('org.gnome.shell.extensions.grand-central-desktop', false)});
let count = 0;
const assert = (ok, message) => { if (!ok) throw new Error(message); count++; };
settings.set_int('panel-width', 387);
settings.set_strv('panel-order', ['browser', 'apps', 'desktop', 'programs', 'documents', 'calculator']);
settings.set_strv('grand-central-desktop-next', ['<Super>n']);
settings.get_child('browser').set_string('home-url', 'https://example.com/home');
settings.get_child('browser').set_int('zoom-percent', 125);
settings.get_child('browser').set_boolean('request-mobile-site', true);
settings.get_child('browser').set_boolean('show-color-picker', false);
settings.get_child('browser').set_boolean('auto-match-page-color', true);
settings.get_child('desktop').set_boolean('show-mounts', true);
settings.get_child('calculator').set_boolean('show-advanced', true);
settings.get_child('notes').set_int('font-size', 20);
const original = exportConfiguration(settings);
const data = JSON.parse(original);
assert(Object.keys(data.settings).length === 8, 'Export contains general settings and every panel');
assert(data.settings.notes && !('text' in data.settings.notes), 'Note appearance is exported without personal note contents');
settings.set_int('panel-width', 420);
settings.get_child('browser').set_int('zoom-percent', 100);
settings.get_child('browser').set_boolean('request-mobile-site', false);
settings.get_child('browser').set_boolean('show-color-picker', true);
settings.get_child('browser').set_boolean('auto-match-page-color', false);
settings.get_child('notes').reset('font-size');
importConfiguration(settings, original);
assert(exportConfiguration(settings) === original, 'All values, including shortcuts and per-panel choices, round-trip');
assert(settings.get_child('browser').get_boolean('request-mobile-site'), 'Mobile-site preference is included in configuration transfer');
assert(!settings.get_child('browser').get_boolean('show-color-picker'), 'Color-picker visibility is included in configuration transfer');
assert(settings.get_child('browser').get_boolean('auto-match-page-color'), 'Automatic page-color matching is included in configuration transfer');
assert(settings.get_child('notes').get_int('font-size') === 20, 'Note font size survives configuration export/import');
function rejects(change, label) {
    const invalid = JSON.parse(original); change(invalid);
    const before = exportConfiguration(settings);
    let rejected = false;
    try { importConfiguration(settings, JSON.stringify(invalid)); } catch { rejected = true; }
    assert(rejected && exportConfiguration(settings) === before, label);
}
rejects(value => value.format = 99, 'Unknown formats are rejected without changes');
rejects(value => value.settings.general['panel-width'] = 100, 'Invalid ranges are rejected before writes');
rejects(value => { value.settings.general['panel-width'] = 400; value.settings.browser['zoom-percent'] = 'bad'; }, 'A later invalid key prevents earlier valid writes');
rejects(value => value.settings.general['panel-width'] = 4294967716, 'Integers cannot overflow into valid values');
rejects(value => value.settings.general['panel-order'] = [1], 'Array values require the expected element type');
rejects(value => value.settings.browser['home-url'] = 'javascript:alert(1)', 'Unsafe home URL schemes are rejected');
rejects(value => value.settings.browser['request-mobile-site'] = 'yes', 'Mobile-site preference requires a boolean');
rejects(value => value.settings.browser['show-color-picker'] = 'no', 'Color-picker visibility requires a boolean');
rejects(value => value.settings.browser['auto-match-page-color'] = 'yes', 'Automatic page-color matching requires a boolean');
rejects(value => value.settings.desktop['background-color'] = 'invalid', 'Invalid colors are rejected');
rejects(value => value.settings.notes['font-size'] = 7, 'Note fonts below the minimum are rejected before writes');
rejects(value => value.settings.notes['font-size'] = 37, 'Note fonts above the maximum are rejected before writes');
rejects(value => value.settings.notes['font-size'] = '20', 'Note font size requires an integer');
rejects(value => value.settings.unknown = {}, 'Unknown sections are rejected');
rejects(value => value.settings.general['unknown-key'] = true, 'Unknown keys are rejected');
const temp = GLib.dir_make_tmp('grand-central-config-XXXXXX');
const file = Gio.File.new_for_path(`${temp}/settings.json`);
await writeConfiguration(file, original);
assert(await readConfiguration(file) === original, 'Private JSON files preserve exact exported values');
assert((file.query_info('unix::mode', Gio.FileQueryInfoFlags.NONE, null).get_attribute_uint32('unix::mode') & 0o077) === 0, 'Export files are private to the user');
file.set_attribute_uint32('unix::mode', 0o644, Gio.FileQueryInfoFlags.NONE, null);
await writeConfiguration(file, original);
assert((file.query_info('unix::mode', Gio.FileQueryInfoFlags.NONE, null).get_attribute_uint32('unix::mode') & 0o077) === 0, 'Overwriting an existing export also keeps it private');
assert(!original.includes('cookies.sqlite') && !original.includes('session-cookies'), 'Configuration exports do not include website credentials');
file.delete(null); Gio.File.new_for_path(temp).delete(null);
print(`Passed ${count} configuration assertions.`);
