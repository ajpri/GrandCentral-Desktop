import Gtk from 'gi://Gtk?version=3.0';
import WebKit from 'gi://WebKit2?version=4.1';
import {polishBrowserMenu} from '../lib/browserMenu.js';
Gtk.init([]);
let count = 0;
const assert = (value, message) => { if (!value) throw new Error(message); count++; };
const menu = new WebKit.ContextMenu();
const actions = ['COPY', 'PASTE', 'COPY_LINK_TO_CLIPBOARD', 'INSPECT_ELEMENT', 'RELOAD'];
const native = actions.map(name => WebKit.ContextMenuItem.new_from_stock_action(WebKit.ContextMenuAction[name]));
native.forEach(item => menu.append(item));
let opened;
polishBrowserMenu(menu, 'https://example.com/link', uri => opened = uri);
const items = menu.get_items();
assert(items.includes(native[0]) && items.includes(native[1]) && items.includes(native[2]), 'Real native clipboard actions survive customization');
assert(!items.includes(native[3]) && !items.includes(native[4]), 'Unrelated browser commands remain omitted');
items[0].get_gaction().activate(null);
assert(opened === 'https://example.com/link', 'Context Open Link uses the selected link in the current view');
assert(items.at(-1).is_separator(), 'Native actions and desktop commands have a separator');
const blank = new WebKit.ContextMenu();
polishBrowserMenu(blank, 'javascript:alert(1)', () => { throw new Error('Unsafe link opened'); });
assert(!blank.get_items().length, 'Blank/unsafe targets do not invent clipboard or executable link actions');
print(`Passed ${count} browser menu checks.`);
